-- INSANITY SOCIETY — Embajadores (códigos, comisiones y pagos)
-- Ejecuta este archivo DESPUÉS de lista-vip.sql:
-- Supabase > SQL Editor > New query > pegar todo > Run.
-- Se puede ejecutar más de una vez sin problema.
--
-- Cómo funciona:
--  * Cada embajador tiene su código de descuento (vive en la tabla cupones,
--    enlazado con embajador_id) y un % de comisión.
--  * Cuando entra un pedido con ese código (por la web o registrado a mano),
--    se le anota automáticamente el embajador y el % de comisión vigente.
--    Si después cambias el %, lo ya ganado no cambia.
--  * La comisión = total pagado del pedido (después del descuento) × % de comisión.
--    Solo cuenta si el pedido está confirmado, enviado o entregado.
--  * Los pagos que le haces a cada embajador se registran en pagos_embajadores.
--  * Todo esto SOLO lo ve el administrador.
-- =========================================================

create table if not exists public.embajadores (
  id             bigint generated by default as identity primary key,
  nombre         text not null check (length(trim(nombre)) between 2 and 80),
  celular        text check (celular is null or celular ~ '^3\d{9}$'),
  instagram      text check (instagram is null or length(instagram) <= 60),
  comision_pct   numeric(5,2) not null default 10 check (comision_pct >= 0 and comision_pct <= 50),
  activo         boolean not null default true,
  notas          text check (notas is null or length(notas) <= 300),
  creado_en      timestamptz not null default now(),
  actualizado_en timestamptz not null default now()
);
drop trigger if exists embajadores_actualizado on public.embajadores;
create trigger embajadores_actualizado before update on public.embajadores
  for each row execute function public.tocar_actualizado();

create table if not exists public.pagos_embajadores (
  id           bigint generated by default as identity primary key,
  embajador_id bigint not null references public.embajadores (id) on delete cascade,
  fecha        timestamptz not null default now(),
  monto        integer not null check (monto > 0),
  nota         text check (nota is null or length(nota) <= 200),
  creado_en    timestamptz not null default now()
);
create index if not exists pagos_embajadores_emb_idx on public.pagos_embajadores (embajador_id);

-- Código de descuento de cada embajador
alter table public.cupones add column if not exists embajador_id bigint
  references public.embajadores (id) on delete set null;
create index if not exists cupones_embajador_idx on public.cupones (embajador_id) where embajador_id is not null;

-- En cada pedido: a qué embajador corresponde y con qué % de comisión
alter table public.pedidos add column if not exists embajador_id bigint
  references public.embajadores (id) on delete set null;
alter table public.pedidos add column if not exists comision_pct numeric(5,2);
create index if not exists pedidos_embajador_idx on public.pedidos (embajador_id) where embajador_id is not null;

-- Anotar el embajador automáticamente según el código usado
create or replace function public.pedidos_embajador()
returns trigger
language plpgsql security definer
set search_path = public
as $$
declare
  v_emb bigint;
  v_pct numeric(5,2);
begin
  if tg_op = 'INSERT' or new.cupon is distinct from old.cupon then
    select c.embajador_id, e.comision_pct into v_emb, v_pct
      from public.cupones c
      join public.embajadores e on e.id = c.embajador_id
     where c.codigo = new.cupon;
    new.embajador_id := v_emb;
    new.comision_pct := v_pct;
  end if;
  return new;
end;
$$;
drop trigger if exists pedidos_embajador on public.pedidos;
create trigger pedidos_embajador before insert or update of cupon on public.pedidos
  for each row execute function public.pedidos_embajador();

-- Pedidos que ya tenían un código de embajador antes de este archivo
update public.pedidos p
   set embajador_id = c.embajador_id,
       comision_pct = e.comision_pct
  from public.cupones c
  join public.embajadores e on e.id = c.embajador_id
 where p.cupon = c.codigo and p.embajador_id is null;

-- ---------- Seguridad: solo el administrador ----------
alter table public.embajadores enable row level security;
alter table public.pagos_embajadores enable row level security;

drop policy if exists "embajadores admin" on public.embajadores;
create policy "embajadores admin" on public.embajadores
  for all to authenticated using ((select public.is_admin())) with check ((select public.is_admin()));
drop policy if exists "pagos embajadores admin" on public.pagos_embajadores;
create policy "pagos embajadores admin" on public.pagos_embajadores
  for all to authenticated using ((select public.is_admin())) with check ((select public.is_admin()));

revoke all on public.embajadores, public.pagos_embajadores from anon;
grant select, insert, update, delete on public.embajadores, public.pagos_embajadores to authenticated;
