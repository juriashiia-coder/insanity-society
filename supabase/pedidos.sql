-- Ejecuta este archivo DESPUÉS de setup.sql, promos.sql e inventario.sql:
-- Supabase > SQL Editor > New query > pegar todo > Run.
-- Se puede ejecutar más de una vez sin problema.
--
-- Cómo funciona:
--  * Cuando un cliente envía su pedido por WhatsApp, la tienda lo guarda aquí
--    como "pendiente" (con los precios recalculados en el servidor).
--  * Desde el panel lo marcas como confirmado / enviado / entregado o cancelado.
--  * Solo cuentan como venta: confirmado, enviado y entregado.
--  * Al pasar a venta se descuentan las unidades del inventario (si el producto
--    lo controla); si se cancela o se borra, se devuelven.
--  * Los datos de los clientes SOLO los ve el administrador.
-- =========================================================

create table if not exists public.pedidos (
  id             bigint generated by default as identity (start with 1001) primary key,
  fecha          timestamptz not null default now(),
  estado         text not null default 'pendiente'
                 check (estado in ('pendiente', 'confirmado', 'enviado', 'entregado', 'cancelado')),
  canal          text not null default 'web'
                 check (canal in ('web', 'whatsapp', 'instagram', 'presencial', 'otro')),
  cliente_nombre text check (length(cliente_nombre) <= 120),
  celular        text check (length(celular) <= 20),
  cedula         text check (length(cedula) <= 20),
  departamento   text check (length(departamento) <= 60),
  ciudad         text check (length(ciudad) <= 80),
  direccion      text check (length(direccion) <= 200),
  barrio         text check (length(barrio) <= 100),
  notas          text check (length(notas) <= 600),
  items          jsonb not null check (jsonb_typeof(items) = 'array' and jsonb_array_length(items) between 1 and 40),
  subtotal       integer not null default 0 check (subtotal >= 0),
  descuento      integer not null default 0 check (descuento >= 0),
  total          integer not null default 0 check (total >= 0),
  cupon          text,
  stock_descontado boolean not null default false,
  creado_en      timestamptz not null default now(),
  actualizado_en timestamptz not null default now()
);
create index if not exists pedidos_fecha_idx on public.pedidos (fecha desc);
create index if not exists pedidos_estado_idx on public.pedidos (estado);

drop trigger if exists pedidos_actualizado on public.pedidos;
create trigger pedidos_actualizado before update on public.pedidos
  for each row execute function public.tocar_actualizado();

-- ---------- Inventario automático ----------
-- Suma (signo = 1) o resta (signo = -1) las unidades de los artículos de un pedido,
-- solo en productos que controlan inventario y en combinaciones color|talla existentes.
create or replace function public.ajustar_stock_pedido(p_items jsonb, p_signo integer)
returns void
language plpgsql security definer
set search_path = public
as $$
declare
  it jsonb;
  k text;
begin
  for it in select * from jsonb_array_elements(p_items) loop
    k := (it->>'color') || '|' || (it->>'talla');
    update public.productos
       set stock = jsonb_set(stock, array[k],
             to_jsonb(greatest(0, coalesce((stock->>k)::int, 0) + p_signo * coalesce((it->>'cantidad')::int, 0))))
     where id = it->>'id' and stock is not null and stock ? k;
  end loop;
end;
$$;
revoke all on function public.ajustar_stock_pedido(jsonb, integer) from public, anon, authenticated;

create or replace function public.pedidos_inventario()
returns trigger
language plpgsql security definer
set search_path = public
as $$
declare
  vendido_nuevo boolean;
begin
  if tg_op = 'DELETE' then
    if old.stock_descontado then perform public.ajustar_stock_pedido(old.items, 1); end if;
    return old;
  end if;

  vendido_nuevo := new.estado in ('confirmado', 'enviado', 'entregado');

  -- Devolver lo que se había descontado (si cambia el estado o los artículos)
  if tg_op = 'UPDATE' and old.stock_descontado
     and (not vendido_nuevo or new.items is distinct from old.items) then
    perform public.ajustar_stock_pedido(old.items, 1);
    new.stock_descontado := false;
  end if;
  if tg_op = 'INSERT' then new.stock_descontado := false; end if;

  -- Descontar si ahora es venta y aún no se había descontado
  if vendido_nuevo and not new.stock_descontado then
    perform public.ajustar_stock_pedido(new.items, -1);
    new.stock_descontado := true;
  end if;
  return new;
end;
$$;

drop trigger if exists pedidos_inventario on public.pedidos;
create trigger pedidos_inventario before insert or update or delete on public.pedidos
  for each row execute function public.pedidos_inventario();

-- ---------- Seguridad ----------
alter table public.pedidos enable row level security;

drop policy if exists "pedidos admin lee" on public.pedidos;
create policy "pedidos admin lee" on public.pedidos
  for select to authenticated using ((select public.is_admin()));
drop policy if exists "pedidos admin crea" on public.pedidos;
create policy "pedidos admin crea" on public.pedidos
  for insert to authenticated with check ((select public.is_admin()));
drop policy if exists "pedidos admin edita" on public.pedidos;
create policy "pedidos admin edita" on public.pedidos
  for update to authenticated using ((select public.is_admin())) with check ((select public.is_admin()));
drop policy if exists "pedidos admin borra" on public.pedidos;
create policy "pedidos admin borra" on public.pedidos
  for delete to authenticated using ((select public.is_admin()));

revoke all on public.pedidos from anon;
grant select, insert, update, delete on public.pedidos to authenticated;

