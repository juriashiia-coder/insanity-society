-- INSANITY SOCIETY — Lista VIP (suscriptores + código personal de bienvenida)
-- Ejecuta este archivo DESPUÉS de cupones-preventa.sql:
-- Supabase > SQL Editor > New query > pegar todo > Run.
-- Se puede ejecutar más de una vez sin problema.
--
-- Cómo funciona:
--  * La configuración (mostrar invitación, regalo, porcentaje, etc.) se guarda en
--    contenido -> clave 'vip' y se cambia desde el panel (pestaña Lista VIP).
--  * Cuando alguien se suscribe, si el regalo está activo y hay porcentaje,
--    se crea un código único (ej. VIP-7K3QM) que SOLO funciona con su celular
--    y una sola vez.
--  * Los datos de los suscriptores SOLO los ve el administrador.
-- =========================================================

-- Configuración inicial: todo apagado y sin porcentaje (se activa desde el panel)
insert into public.contenido (clave, valor)
values ('vip', jsonb_build_object(
  'activo', false,
  'regalo_activo', false,
  'porcentaje', null,
  'minimo_compra', 0,
  'dias_validez', null,
  'codigos_pausados', false,
  'titulo', 'Únete a la Sociedad',
  'texto', 'Entérate primero de lanzamientos, preventas y ofertas exclusivas.'
))
on conflict (clave) do nothing;

create table if not exists public.suscriptores (
  id         bigint generated by default as identity primary key,
  creado_en  timestamptz not null default now(),
  nombre     text check (length(nombre) <= 80),
  celular    text not null unique check (celular ~ '^3\d{9}$'),
  correo     text check (length(correo) <= 120),
  codigo     text,
  origen     text check (length(origen) <= 30),
  activo     boolean not null default true
);
create index if not exists suscriptores_creado_idx on public.suscriptores (creado_en desc);

alter table public.suscriptores enable row level security;
drop policy if exists "suscriptores admin lee" on public.suscriptores;
create policy "suscriptores admin lee" on public.suscriptores
  for select to authenticated using ((select public.is_admin()));
drop policy if exists "suscriptores admin edita" on public.suscriptores;
create policy "suscriptores admin edita" on public.suscriptores
  for update to authenticated using ((select public.is_admin())) with check ((select public.is_admin()));
drop policy if exists "suscriptores admin borra" on public.suscriptores;
create policy "suscriptores admin borra" on public.suscriptores
  for delete to authenticated using ((select public.is_admin()));
revoke all on public.suscriptores from anon;
grant select, update, delete on public.suscriptores to authenticated;

-- Suscribirse desde la tienda. Devuelve el código (si hay regalo) y su estado.
create or replace function public.suscribir_vip(p_nombre text, p_celular text, p_correo text default null, p_origen text default null)
returns jsonb
language plpgsql security definer
set search_path = public
as $$
declare
  cfg jsonb;
  cel text := regexp_replace(coalesce(p_celular, ''), '\D', '', 'g');
  v_correo text := nullif(lower(trim(coalesce(p_correo, ''))), '');
  s public.suscriptores%rowtype;
  existia boolean;
  pct integer;
  minimo integer;
  dias integer;
  cod text;
  alfabeto text := 'ABCDEFGHJKMNPQRSTUVWXYZ23456789';
  cu public.cupones%rowtype;
  usado boolean := false;
begin
  select valor into cfg from public.contenido where clave = 'vip';
  if cfg is null or not coalesce((cfg->>'activo')::boolean, false) then
    raise exception 'VIP_INACTIVO';
  end if;
  if cel ~ '^57\d{10}$' then cel := substr(cel, 3); end if;
  if cel !~ '^3\d{9}$' then raise exception 'CELULAR_INVALIDO'; end if;
  if v_correo is not null and (length(v_correo) > 120 or v_correo !~ '^[^@\s]+@[^@\s]+\.[^@\s]+$') then
    raise exception 'CORREO_INVALIDO';
  end if;
  -- Freno contra registros masivos automáticos
  if (select count(*) from public.suscriptores where creado_en > now() - interval '1 minute') >= 30 then
    raise exception 'INTENTA_LUEGO';
  end if;

  select * into s from public.suscriptores where celular = cel;
  existia := found;
  if existia then
    update public.suscriptores
       set nombre = coalesce(nullif(left(trim(coalesce(p_nombre, '')), 80), ''), nombre),
           correo = coalesce(v_correo, suscriptores.correo),
           activo = true
     where id = s.id
    returning * into s;
  else
    insert into public.suscriptores (nombre, celular, correo, origen)
    values (nullif(left(trim(coalesce(p_nombre, '')), 80), ''), cel, v_correo, left(p_origen, 30))
    returning * into s;
  end if;

  -- Regalo de bienvenida: un código personal por celular (solo uno en toda la vida)
  if s.codigo is null and coalesce((cfg->>'regalo_activo')::boolean, false) then
    pct := nullif(cfg->>'porcentaje', '')::integer;
    if pct between 1 and 90 then
      minimo := coalesce(nullif(cfg->>'minimo_compra', '')::integer, 0);
      dias := nullif(cfg->>'dias_validez', '')::integer;
      loop
        cod := 'VIP-' || (select string_agg(substr(alfabeto, 1 + floor(random() * length(alfabeto))::int, 1), '')
                            from generate_series(1, 5));
        exit when not exists (select 1 from public.cupones where codigo = cod);
      end loop;
      insert into public.cupones (codigo, tipo, valor, minimo_compra, vence, activo, nota,
                                  usos_por_cliente, usos_maximos, celular_vip)
      values (cod, 'porcentaje', pct, greatest(minimo, 0),
              case when dias > 0 then now() + make_interval(days => dias) end,
              true, 'Lista VIP · ' || cel, 1, 1, cel);
      update public.suscriptores set codigo = cod where id = s.id returning * into s;
    end if;
  end if;

  if s.codigo is not null then
    select * into cu from public.cupones where codigo = s.codigo;
    usado := exists (select 1 from public.pedidos p where p.cupon = s.codigo and p.estado <> 'cancelado');
  end if;

  return jsonb_build_object(
    'nuevo', not existia,
    'codigo', s.codigo,
    'porcentaje', cu.valor,
    'minimo_compra', cu.minimo_compra,
    'vence', cu.vence,
    'usado', usado,
    'disponible', s.codigo is not null and not usado and coalesce(cu.activo, false)
                  and (cu.vence is null or cu.vence > now())
                  and not coalesce((cfg->>'codigos_pausados')::boolean, false)
  );
end;
$$;
revoke all on function public.suscribir_vip(text, text, text, text) from public;
grant execute on function public.suscribir_vip(text, text, text, text) to anon, authenticated;
